"""
AEGIS Multi-Step Workflow Agent
Executes structured multi-phase objectives with intermediate validation and supervision checkpoints.
"""

import re
from typing import Dict, Any, List, Tuple
from aegis.actions.web_search import WebSearchEngine
from aegis.actions.file_manager import FileManager

class WorkflowAgent:
    """Orchestrates multi-step workflows with step-by-step supervision awareness."""

    def __init__(self, file_manager: FileManager, search_engine: WebSearchEngine):
        self.file_manager = file_manager
        self.search_engine = search_engine

    def execute_python_resource_workflow(self, goal: str = "Python") -> Dict[str, Any]:
        """
        Demonstrates the canonical SIH scenario:
        1. Search 3 resources
        2. Evaluate and format
        3. Prepare file creation proposal
        """
        # Clean topic from goal
        lower = goal.lower()
        if "python" in lower:
            topic = "Python"
        elif "javascript" in lower or "js" in lower:
            topic = "JavaScript"
        elif "machine learning" in lower or "ai" in lower:
            topic = "Machine Learning"
        else:
            # Strip common action verbs
            clean = re.sub(r'^(find|search|research|gather|organize|create|summarize)\s*', '', goal, flags=re.IGNORECASE).strip()
            topic = clean.title() if clean else "Research Topic"

        # Step 1: Search
        search_res = self.search_engine.search(f"Top best {topic} tutorials documentation books 2026", limit=3)
        resources = search_res.get("results", [])

        # Step 2: Formulate Curated Content
        content_lines = [
            f"# Curated Executive Guide: Learning {topic}",
            f"*Generated by AEGIS Multi-Step Agent*\n",
            "## Recommended High-Yield Resources\n"
        ]

        if resources:
            for idx, r in enumerate(resources, 1):
                content_lines.append(f"### {idx}. {r['title']}")
                content_lines.append(f"- **Reference**: [{r['url']}]({r['url']})")
                content_lines.append(f"- **Summary**: {r['snippet']}\n")
        else:
            content_lines.extend([
                f"### 1. Official {topic} Documentation",
                "- Complete language reference, library tour, and standard documentation.\n",
                f"### 2. Industry Standard Best Practices for {topic}",
                "- In-depth practical articles, patterns, data structures, and best practices.\n",
                f"### 3. Practical Hands-on Projects in {topic}",
                "- Hands-on automation, scripting, and production pipelines."
            ])

        content_lines.append("## Learning Roadmap & Milestones")
        content_lines.append("1. **Week 1-2**: Core Syntax, Control Flow, and Functions")
        content_lines.append("2. **Week 3-4**: Data Structures, OOP, and Modular Architecture")
        content_lines.append("3. **Week 5-6**: APIs, External Integration, and Automation Workflows")
        content_lines.append("4. **Week 7+**: Agentic Systems and Production Deployments")

        full_content = "\n".join(content_lines)
        target_filename = f"{topic.lower().replace(' ', '_')}_learning_guide.md"

        return {
            "steps_completed": [
                {"step": 1, "description": f"Gathered verified web resources on {topic}."},
                {"step": 2, "description": "Synthesized structured milestones and study schedule."},
                {"step": 3, "description": f"Prepared final guide file '{target_filename}'."}
            ],
            "proposed_file": {
                "filename": target_filename,
                "content": full_content,
                "size_chars": len(full_content)
            },
            "summary": f"Compiled verified {topic} roadmap with 3 curated resources and a 4-milestone plan."
        }
